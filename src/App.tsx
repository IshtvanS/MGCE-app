    return Object.entries(groups)
      .map(([monthIdx, items]) => ({
        monthIdx: Number(monthIdx),
        monthName: UK_MONTHS_NOM[Number(monthIdx)],
        items,
      }))
      .sort((a, b) => a.monthIdx - b.monthIdx);
