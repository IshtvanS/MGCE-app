    return PASTORAL_CALENDAR_2026.filter((item) => {
      const matchesMonth =
        selectedMonth === 'all' || item.month === selectedMonth;
      const matchesQuery =
        !q ||
        item.title.toLowerCase().includes(q) ||
        item.location.toLowerCase().includes(q) ||
        item.responsible.toLowerCase().includes(q) ||
        item.dateLabel.toLowerCase().includes(q);
      return matchesMonth && matchesQuery;
    });
